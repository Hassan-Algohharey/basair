// Scoped editorial paraphrases of the scanned Kuwait encyclopedia, not quotations or personal fatwas.
private fun reviewedIssue(
    id: String, title: String, topic: String, scope: String, volume: Int, pages: String,
    vararg summaries: String
): Comparison {
    require(summaries.size == 4)
    return Comparison(id, title, topic, scope,
        listOf("الحنفي", "المالكي", "الشافعي", "الحنبلي").zip(summaries.toList()).map { (school, summary) ->
            SchoolOpinion(school, summary, listOf(kuwaitReference(volume, pages, pages.substringBefore('–').toInt())))
        })
}

