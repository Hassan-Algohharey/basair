"""Validate source-title / edition-page mappings and generate the offline study index."""
import hashlib
import json
import re
from pathlib import Path
from pypdf import PdfReader

ROOT = Path(__file__).resolve().parents[1]
books = {b['id']: b for b in json.loads((ROOT / 'content/books.json').read_text(encoding='utf-8'))}
media = {i['id']: i for i in json.loads((ROOT / 'content/media/catalog.json').read_text(encoding='utf-8'))['items']}
links = json.loads((ROOT / 'content/media/book-lessons.json').read_text(encoding='utf-8'))['links']
assert len({link['id'] for link in links}) == len(links)

def normalized(text):
    return re.sub(r'[\W_\u064b-\u065f\u0670\u0640]', '', text)

readers = {}
for link in links:
    b, item = books[link['bookId']], media[link['itemId']]
    assert b['id'] in item['bookIds'] and item.get('seriesId')
    assert link['bookSha256'] == b['sha256']
    assert link['sourceUrl'] == item['url'] and link['httpStatus'] == 200
    assert len(link['pageSha256']) == 64 and link['pageVisuallyReviewed'] is True
    assert link['title'] and link['englishTitle'] and link['printedPage'] and link['reviewedOn']
    assert 1 <= link['pdfPage'] <= b['pages']
    assert normalized(link['sourceAnchor']) in normalized(link['sourceHeading'])
    if b['id'] not in readers:
        source = ROOT / 'content/originals' / Path(b['asset']).name
        assert hashlib.sha256(source.read_bytes()).hexdigest() == b['sha256']
        readers[b['id']] = PdfReader(source)
    assert normalized(link['sourceAnchor']) in normalized(readers[b['id']].pages[link['pdfPage'] - 1].extract_text())

def q(v):
    return json.dumps(v, ensure_ascii=False).replace('$', '\\$')

lines = ['package com.algohary.basair', '', '// Generated by tools/package_book_lessons.py; mappings are edition-specific.',
         'internal val reviewedBookLessons = listOf(']
for link in links:
    keys = ['id', 'itemId', 'bookId', 'title', 'englishTitle', 'pdfPage', 'printedPage', 'bookSha256', 'sourceUrl']
    lines.append('    BookLessonLink(' + ', '.join(str(link[k]) if k == 'pdfPage' else q(link[k]) for k in keys) + '),')
lines += [')', '']
(ROOT / 'app/src/main/java/com/algohary/basair/BookLessonData.kt').write_text('\n'.join(lines), encoding='utf-8')
print(f'Validated {len(links)} passage links across {len(readers)} unchanged book editions; source title and page anchors match.')
