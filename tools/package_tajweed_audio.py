"""Validate reviewed Tajweed audio evidence and generate compact playback metadata."""
import hashlib
import json
from pathlib import Path
from urllib.parse import urlparse

root = Path(__file__).resolve().parents[1]
data = json.loads((root/'content/tajweed-media/catalog.json').read_text('utf-8'))
quran = json.loads((root/'app/src/main/assets/quran-index.json').read_text('utf-8'))
assert len(data['audio']) == 5
assert len({r['id'] for r in data['audio']}) == 5
for proof in data['evidence']:
    raw = (root/proof['path']).read_bytes()
    assert len(raw) == proof['bytes'] and hashlib.sha256(raw).hexdigest() == proof['sha256']
for row in data['audio']:
    assert row['kind'] == 'lesson' and row['downloadAllowed'] and not row['commercialUseAllowed']
    assert row['riwayaStatus'] == 'not-stated-by-source'
    assert urlparse(row['url']).hostname == 'd1.islamhouse.com' and row['url'].startswith('https://')
    assert row['url'].endswith('.mp3') and row['mimeType'] == 'audio/mpeg'
    assert 0 < row['bytes'] < 500_000_000
    assert [p['offset'] for p in row['probes']] == [0,row['bytes']//2,row['bytes']-4096]
    assert all(p['httpStatus']==206 and p['bytes']==4096 and len(p['sha256'])==64 for p in row['probes'])
    if row['quranStart']:
        anchor = row['quranStart']
        surah = quran['surahs'][anchor['surah']-1]
        assert 1 <= anchor['ayah'] <= surah['ayahCount']

def q(value):
    return json.dumps(value,ensure_ascii=False).replace('$','\\$')

lines = ['package com.algohary.basair','','// Generated by tools/package_tajweed_audio.py; original recordings stay on IslamHouse.','internal object TajweedAudioCatalog {','    val lessons = listOf(']
for r in data['audio']:
    anchor=r['quranStart']
    lines.append('        TajweedAudioLesson('+', '.join(q(r[k]) for k in ['id','title','englishTitle','speaker','englishSpeaker'])+
        ', topicIds = listOf('+', '.join(q(x) for x in r['topicIds'])+'), bookIds = listOf('+', '.join(q(x) for x in r['bookIds'])+')'+
        (f', surah = {anchor["surah"]}, ayah = {anchor["ayah"]}' if anchor else '')+'),')
lines += ['    )','    val recordings = listOf(']
for r in data['audio']:
    lines.append('        Audiobook('+', '.join(q(v) for v in [r['id'],r['title'],r['englishTitle'],'',r['speaker'],r['englishSpeaker']])+
        ', bookIds = listOf('+', '.join(q(x) for x in r['bookIds'])+'), coverage = "partial", '+
        'coverageNote = '+q('درس تطبيقي كامل من سلسلة أحمد عامر، الحلقة '+str(r['sourceEpisode'])+' بحسب المصدر؛ فهرسة السلسلة جزئية. لم يقابل التسجيل كاملًا سماعًا. لا توقيت مطابق للصفحات أو الآيات.')+', '+
        'englishCoverageNote = '+q(f'Full practice lesson {r["sourceEpisode"]} as listed by the source; only part of the series is indexed. The entire recording has not been reviewed by listening. No page or verse timing alignment.')+', '+
        'sourceUrl = '+q(r['sourceUrl'])+', licenseName = '+q('إذن نشر غير تجاري مع نسبة المصدر وحفظ المحتوى')+', licenseUrl = '+q(data['licenseUrl'])+', '+
        'rightsNote = '+q('دار الإسلام: نشر غير تجاري مع نسبة المصدر وعدم تغيير المحتوى. لا إعادة استضافة أو اقتصاص للتسجيل؛ التنزيل نسخة خاصة داخل التطبيق. الإذن التجاري المستقل غير مثبت. لم يبين المصدر رواية الأداء؛ يفتح المصحف برواية حفص دون ادعاء مزامنة أو مطابقة جميع أوجه الأداء.')+', '+
        'englishRightsNote = '+q('IslamHouse: noncommercial reuse with attribution and unchanged content. No rehosting or trimming; optional downloads are private app copies. Separate commercial permission is not established. The source does not state the recitation riwaya; the Quran reader uses Hafs, without timing or all-reading-variant alignment claims.')+', '+
        'tracks = listOf(AudioTrack('+', '.join(q(v) for v in [r['id']+'-full',r['title'],r['englishTitle'],r['url']])+f', sequence = 1, byteSize = {r["bytes"]}L)), downloadAllowed = true, kind = "lesson"),')
lines += ['    )','}','']
(root/'app/src/main/java/com/algohary/basair/TajweedAudioData.kt').write_text('\n'.join(lines),encoding='utf-8')
print('PASS: 5 original practice lessons, 4 source-based Quran anchors, source/rights evidence and 15 audio probes.')
