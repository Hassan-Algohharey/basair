"""Generate the compact audiobook index from reviewed source and rights evidence."""
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
catalog = json.loads((ROOT / 'content/audiobooks/catalog.json').read_text('utf-8'))
audit = json.loads((ROOT / 'content/audiobooks/audit.json').read_text('utf-8'))
books = {b['id'] for b in json.loads((ROOT / 'content/books.json').read_text('utf-8'))}
recordings = catalog['recordings']
assert len({r['id'] for r in recordings}) == len(recordings)
assert {r['id'] for r in recordings} == {r['recordingId'] for r in audit['recordings']}
assert len(audit['rightsDecision']['sourcePageSha256']) == 64
ids = set()
def url(value, hosts):
    parsed = urlparse(value)
    assert parsed.scheme == 'https' and parsed.hostname in hosts
    assert parsed.username is None and parsed.password is None and parsed.port in (None, 443)
for recording in recordings:
    assert recording['kind'] == 'reading' and recording['language'] == 'ar'
    assert recording['coverage'] in ('complete-as-listed', 'partial')
    assert recording['bookIds'] and set(recording['bookIds']) <= books
    url(recording['sourceUrl'], {'islamhouse.com'})
    url(recording['licenseUrl'], {'d1.islamhouse.com'})
    assert recording['licenseUrl'] == audit['rightsDecision']['licenseUrl']
    assert recording['rightsNote'] and recording['englishRightsNote'] and recording['reader']
    evidence = next(r for r in audit['recordings'] if r['recordingId'] == recording['id'])
    assert evidence['sourceHttpStatus'] == 200 and len(evidence['sourcePageSha256']) == 64
    assert evidence['sourceUrl'] == recording['sourceUrl']
    assert [t['sequence'] for t in recording['tracks']] == list(range(1, len(recording['tracks']) + 1))
    for track in recording['tracks']:
        assert track['id'] not in ids
        ids.add(track['id'])
        url(track['url'], {'d1.islamhouse.com'})
        assert track['url'].endswith('.mp3') and 0 < track['byteSize'] < 500_000_000
        assert track['mimeType'] == 'audio/mpeg'
        probe = evidence['audioProbe']
        assert probe['url'] == track['url'] == probe['finalUrl']
        assert probe['status'] == 206 and probe['totalBytes'] == track['byteSize']
        assert probe['contentType'] == track['mimeType']
def q(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')
lines = ['package com.algohary.basair', '', '// Generated by tools/package_audiobooks.py. Recordings remain on the original host.',
         'internal object AudiobookCatalog {', '    val recordings = listOf(']
for r in recordings:
    fields = ['id', 'title', 'englishTitle', 'author', 'reader', 'englishReader']
    value = '        Audiobook(' + ', '.join(q(r[k]) for k in fields)
    value += ', bookIds = listOf(' + ', '.join(q(b) for b in r['bookIds']) + ')'
    for field in ['coverage', 'coverageNote', 'englishCoverageNote', 'sourceUrl', 'licenseName', 'licenseUrl', 'rightsNote', 'englishRightsNote']:
        value += ', ' + field + ' = ' + q(r[field])
    value += ', downloadAllowed = ' + str(r['downloadAllowed']).lower() + ', tracks = listOf('
    value += ', '.join('AudioTrack(' + ', '.join(q(t[k]) for k in ['id', 'title', 'englishTitle', 'url']) + ', sequence = ' + str(t['sequence']) + ', byteSize = ' + str(t['byteSize']) + 'L, mimeType = ' + q(t['mimeType']) + ')' for t in r['tracks'])
    lines.append(value + ')),')
lines += ['    )', '}', '']
(ROOT / 'app/src/main/java/com/algohary/basair/AudiobookData.kt').write_text('\n'.join(lines), encoding='utf-8')
print(f'PASS: {len(recordings)} readings, {len(ids)} tracks, source/rights/book links and audio sizes verified.')
