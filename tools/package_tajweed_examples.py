"""Generate canonical metadata for unchanged official Hafs recitations, never audio assets."""
import hashlib
import json
import argparse
from pathlib import Path
from urllib.parse import urlparse

root = Path(__file__).resolve().parents[1]
data = json.loads((root/'content/tajweed-examples/catalog.json').read_text('utf-8'))
parser = argparse.ArgumentParser()
parser.add_argument('--verify-audio-dir', type=Path, help='Optional private folder containing <surah>.mp3 originals')
args = parser.parse_args()
for proof in data['evidence']:
    raw = (root/proof['path']).read_bytes()
    assert len(raw) == proof['bytes'] and hashlib.sha256(raw).hexdigest() == proof['sha256']
playlist = json.loads((root/'content/tajweed-examples/playlist.json').read_text('utf-8'))
assert data['timingScope'] == 'whole-original-surah-only'
assert data['riwaya'] == 'Hafs an Asim'
assert len(data['recordings']) == 4 and len(data['examples']) == 6
quran = {}
for path in (root/'content/quran/ede83bce2ddc925c').glob('*.json'):
    for ayah in json.loads(path.read_text('utf-8'))['ayahs']:
        quran[(ayah['surah'], ayah['ayah'])] = ayah['text']
for recording in data['recordings']:
    assert playlist[recording['surah']-1]['audio'] == recording['url']
    assert urlparse(recording['url']).hostname == 'download.qurancomplex.gov.sa'
    assert 0 < recording['durationMs'] < 60_000 and recording['bytes'] > 0
    if args.verify_audio_dir:
        raw = (args.verify_audio_dir/f'{recording["surah"]}.mp3').read_bytes()
        assert len(raw) == recording['bytes'] and hashlib.sha256(raw).hexdigest() == recording['sha256']
        # These four originals are MPEG-2 Layer III, 64 kb/s, 24 kHz, 576 samples/frame.
        offset = frames = 0
        while offset + 4 <= len(raw):
            header = int.from_bytes(raw[offset:offset+4], 'big')
            if header >> 21 == 2047 and (header >> 19) & 3 == 2 and (header >> 17) & 3 == 1 and (header >> 12) & 15 == 8 and (header >> 10) & 3 == 1:
                size = 72 * 64_000 // 24_000 + ((header >> 9) & 1)
                assert offset + size <= len(raw)
                frames += 1
                offset += size
            else:
                offset += 1
        assert frames * 24 == recording['durationMs']
for example in data['examples']:
    assert (example['surah'], example['ayah']) in quran
    assert example['recordingId'] in {r['id'] for r in data['recordings']}

def q(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')

lines = ['package com.algohary.basair', '', '// Generated by tools/package_tajweed_examples.py; audio stays on the official source.',
         'internal object TajweedExamples {', '    val examples = listOf(']
for e in data['examples']:
    lines.append('        TajweedExample('+', '.join(q(e[k]) for k in ['id','topic','word','englishTitle'])+
                 f', {e["surah"]}, {e["ayah"]}, '+q(e['recordingId'])+'),')
lines += ['    )', '    val recordings = listOf(']
for r in data['recordings']:
    note = 'حفص عن عاصم — سورة كاملة من المصدر دون اقتصاص؛ الأمثلة تحدد الآية والكلمة فقط، ولا تحدد توقيت الكلمة. يمكن تكرار السورة كاملة.'
    en = 'Hafs an Asim — the complete original surah, unchanged. Examples identify a verse and word, without word timing. Repeat plays the entire surah.'
    lines.append('        Audiobook('+', '.join(q(v) for v in [r['id'],r['title'],r['englishTitle'],'',data['reader'],data['englishReader']])+
        ', bookIds = listOf("tuhfat-atfal", "jazariyyah"), coverage = "complete-surah", coverageNote = '+q(note)+
        ', englishCoverageNote = '+q(en)+', sourceUrl = '+q(data['sourceUrl'])+
        ', licenseName = "مجمع الملك فهد — إتاحة عامة مجانية للتطبيقات", licenseUrl = '+q(data['licenseUrl'])+
        ', rightsNote = "المصدر: مجمع الملك فهد لطباعة المصحف الشريف. تصريح عام بالاستخدام المجاني في التطبيقات داخل المملكة وخارجها. نسخة المصدر كاملة دون تعديل؛ التنزيل اختياري في مساحة التطبيق الخاصة.",'+
        ' englishRightsNote = "Source: King Fahd Glorious Quran Printing Complex. General permission for free use in applications inside and outside Saudi Arabia. Original complete audio, unchanged; optional private app download.",'+
        ' tracks = listOf(AudioTrack('+', '.join(q(v) for v in [r['id']+'-full',r['title'],r['englishTitle'],r['url']])+
        f', sequence = 1, durationMs = {r["durationMs"]}L, byteSize = {r["bytes"]}L, sha256 = '+q(r['sha256'])+')), downloadAllowed = true, kind = "recitation"),')
lines += ['    )', '}', '']
(root/'app/src/main/java/com/algohary/basair/TajweedExamplesData.kt').write_text('\n'.join(lines), encoding='utf-8')
print('PASS: 4 official unchanged Hafs surahs, 6 verse/topic references; no word timings claimed.')
