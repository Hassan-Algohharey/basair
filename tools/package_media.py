"""Validate the reviewed external-media index and generate offline Kotlin metadata."""
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
catalog = json.loads((ROOT / 'content/media/catalog.json').read_text(encoding='utf-8'))
audit = json.loads((ROOT / 'content/media/audit.json').read_text(encoding='utf-8'))
scholars = catalog['scholars']
items = catalog['items']
assert len({s['id'] for s in scholars}) == len(scholars)
assert len({i['id'] for i in items}) == len(items)
books = json.loads((ROOT / 'content/books.json').read_text(encoding='utf-8'))
if isinstance(books, dict):
    books = books['books']
book_ids = {b['id'] for b in books}
def url(value):
    parsed = urlparse(value)
    assert parsed.scheme == 'https' and parsed.hostname in {'binbaz.org.sa', 'almunajjid.com'}
    assert not parsed.username and not parsed.password and parsed.port in (None, 443)
for scholar in scholars:
    url(scholar['officialUrl']); url(scholar['verificationUrl'])
for item in items:
    assert item['scholarId'] in {s['id'] for s in scholars}
    assert item['type'] in {'lesson', 'sermon', 'short'}
    assert item['mediaKind'] in {'audio', 'video'}
    assert set(item['bookIds']) <= book_ids
    assert item['sourceNote'] and item['englishSourceNote'] and item['verifiedOn']
    url(item['url'])
    evidence = next(a for a in audit['items'] if a['itemId'] == item['id'])
    assert evidence['url'] == item['url'] and evidence['httpStatus'] == 200
    assert evidence['mediaElementPresent'] and len(evidence['pageSha256']) == 64
    assert evidence['reviewedOn'] == item['verifiedOn']
assert {a['itemId'] for a in audit['items']} == {i['id'] for i in items}
def q(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')
lines = ['package com.algohary.basair', '', '// Generated by tools/package_media.py from the reviewed source index.',
         'internal object MediaCatalog {', '    val scholars = listOf(']
for s in scholars:
    lines.append('        MediaUiScholar(' + ', '.join(q(v) for v in [s['id'], s['name'], '', urlparse(s['officialUrl']).hostname, s['verificationUrl'], s['englishName']]) + '),')
lines += ['    )', '    val items = listOf(']
for i in items:
    lines.append('        MediaUiItem(' + ', '.join(q(v) for v in [i['id'], i['scholarId'], i['title'], i['type'], ' · '.join(i['topics']), i.get('seriesTitle',''), urlparse(i['url']).hostname, i['url']]) + ', bookIds = listOf(' + ', '.join(q(b) for b in i['bookIds']) + '), searchAliases = ' + q(i['englishTitle'] + ' ' + i['mediaKind']) + ', sourceNote = ' + q(i['sourceNote']) + ', englishSourceNote = ' + q(i['englishSourceNote']) + ', format = ' + q(i['mediaKind']) + '),')
lines += ['    )', '    val allowedUrls = items.map { it.sourceUrl }.toSet() + scholars.map { it.sourceUrl }', '}', '']
(ROOT / 'app/src/main/java/com/algohary/basair/MediaData.kt').write_text('\n'.join(lines), encoding='utf-8')
print(f'Validated {len(scholars)} scholars, {len(items)} media records and all linked book IDs.')
