"""Validate the reviewed external-media index and generate offline Kotlin metadata."""
import json
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
catalog = json.loads((ROOT / 'content/media/catalog.json').read_text(encoding='utf-8'))
audit = json.loads((ROOT / 'content/media/audit.json').read_text(encoding='utf-8'))
scholars = catalog['scholars']
items = catalog['items']
series = catalog.get('series', [])
assert len({s['id'] for s in series}) == len(series)
assert {a['seriesId'] for a in audit.get('seriesEvidence', [])} == {s['id'] for s in series}
assert len({s['id'] for s in scholars}) == len(scholars)
assert len({i['id'] for i in items}) == len(items)
books = json.loads((ROOT / 'content/books.json').read_text(encoding='utf-8'))
if isinstance(books, dict):
    books = books['books']
book_ids = {b['id'] for b in books}
def url(value):
    parsed = urlparse(value)
    assert parsed.scheme == 'https' and parsed.hostname in {'binbaz.org.sa', 'almunajjid.com', 'sh-albarrak.com'}
    assert not parsed.username and not parsed.password and parsed.port in (None, 443)
for scholar in scholars:
    url(scholar['officialUrl']); url(scholar['verificationUrl'])
for entry in series:
    assert entry['scholarId'] in {s['id'] for s in scholars}
    assert set(entry['bookIds']) <= book_ids
    assert entry['coverage'] in {'partial', 'complete'}
    assert entry['coverageNote'] and entry['englishCoverageNote']
    url(entry['sourceUrl'])
    episodes = [i for i in items if i.get('seriesId') == entry['id']]
    assert episodes
    numbers = [i['episodeNumber'] for i in episodes if i.get('episodeNumber') is not None]
    assert all(isinstance(n, int) and n > 0 for n in numbers) and len(numbers) == len(set(numbers))
    if entry['expectedEpisodes'] is not None:
        assert isinstance(entry['expectedEpisodes'], int) and entry['expectedEpisodes'] > 0
        assert all(n <= entry['expectedEpisodes'] for n in numbers)
    if entry['coverage'] == 'complete':
        assert entry['expectedEpisodes'] and len(episodes) == entry['expectedEpisodes']
        assert sorted(numbers) == list(range(1, entry['expectedEpisodes'] + 1))
    evidence = next(a for a in audit['seriesEvidence'] if a['seriesId'] == entry['id'])
    assert evidence['sourceUrl'] == entry['sourceUrl'] and evidence['httpStatus'] == 200
    assert len(evidence['pageSha256']) == 64 and evidence['coverage'] == entry['coverage']
    assert sorted(evidence['catalogEpisodeNumbers']) == sorted(numbers)
    if entry['coverage'] == 'complete':
        assert evidence['sourceStatus'] == 'COMPLETE' and evidence['listedEpisodeCount'] == entry['expectedEpisodes']
        assert evidence['nextPage'] is None
for item in items:
    if item.get('seriesId'):
        group = next(s for s in series if s['id'] == item['seriesId'])
        assert item['scholarId'] == group['scholarId'] and set(item['bookIds']) == set(group['bookIds'])
    assert item['topics'] and all(t.strip() for t in item['topics'])
    assert len(item.get('englishTopics', [])) in (0, len(item['topics']))
    assert all(t.strip() for t in item.get('englishTopics', []))
    assert item['scholarId'] in {s['id'] for s in scholars}
    assert item['type'] in {'lesson', 'sermon', 'short'}
    assert item['mediaKind'] in {'audio', 'video'}
    assert set(item['bookIds']) <= book_ids
    assert item['sourceNote'] and item['englishSourceNote'] and item['verifiedOn']
    url(item['url'])
    evidence = next(a for a in audit['items'] if a['itemId'] == item['id'])
    assert evidence['url'] == item['url'] and evidence['httpStatus'] == 200
    assert evidence['mediaElementPresent'] and len(evidence['pageSha256']) == 64
    assert evidence['reviewedOn'] == item['verifiedOn']
assert {a['itemId'] for a in audit['items']} == {i['id'] for i in items}
def q(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')
lines = ['package com.algohary.basair', '', '// Generated by tools/package_media.py from the reviewed source index.',
         'internal object MediaCatalog {', '    val scholars = listOf(']
for s in scholars:
    lines.append('        MediaUiScholar(' + ', '.join(q(v) for v in [s['id'], s['name'], '', urlparse(s['officialUrl']).hostname, s['verificationUrl'], s['englishName']]) + '),')
lines += ['    )', '    val series: List<MediaUiSeries> = listOf(']
for entry in series:
    lines.append('        MediaUiSeries(' + ', '.join(q(entry[k]) for k in ['id', 'title', 'englishTitle', 'scholarId']) + ', bookIds = listOf(' + ', '.join(q(b) for b in entry['bookIds']) + '), sourceUrl = ' + q(entry['sourceUrl']) + ', coverage = ' + q(entry['coverage']) + ', expectedEpisodes = ' + str(entry['expectedEpisodes'] or 'null') + ', coverageNote = ' + q(entry['coverageNote']) + ', englishCoverageNote = ' + q(entry['englishCoverageNote']) + '),')
lines += ['    )', '    val items = listOf(']
for i in items:
    lines.append('        MediaUiItem(' + ', '.join(q(v) for v in [i['id'], i['scholarId'], i['title'], i['type'], ' · '.join(i['topics']), i.get('seriesTitle',''), urlparse(i['url']).hostname, i['url']]) + ', bookIds = listOf(' + ', '.join(q(b) for b in i['bookIds']) + '), searchAliases = ' + q(i['englishTitle'] + ' ' + i['mediaKind']) + ', sourceNote = ' + q(i['sourceNote']) + ', englishSourceNote = ' + q(i['englishSourceNote']) + ', format = ' + q(i['mediaKind']) + ', seriesId = ' + (q(i['seriesId']) if i.get('seriesId') else 'null') + ', episodeNumber = ' + str(i.get('episodeNumber') or 'null') + ', topics = listOf(' + ', '.join(q(t) for t in i['topics']) + '), englishTopics = listOf(' + ', '.join(q(t) for t in i.get('englishTopics', [])) + ')),')
lines += ['    )', '    val allowedUrls = items.map { it.sourceUrl }.toSet() + scholars.map { it.sourceUrl } + series.map { it.sourceUrl }', '}', '']
(ROOT / 'app/src/main/java/com/algohary/basair/MediaData.kt').write_text('\n'.join(lines), encoding='utf-8')
print(f'Validated {len(scholars)} scholars, {len(items)} media records, {len(series)} series and all linked book IDs.')
