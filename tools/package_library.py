"""Validate complete approved originals, package unchanged assets, and generate Kotlin metadata."""
import hashlib
import json
import shutil
from pathlib import Path
from pypdf import PdfReader

ROOT = Path(__file__).resolve().parent.parent
books = json.loads((ROOT / 'content/books.json').read_text(encoding='utf-8'))
assert {b['subject'] for b in books} == {'fiqh', 'aqidah', 'hadith', 'sirah', 'tafsir', 'salaf', 'tazkiyah', 'tajweed'}
assert len({b['id'] for b in books}) == len(books)
metadata = []
rows = []
def kotlin(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')

for book in books:
    source = ROOT / 'content/incoming' / book['inputFile']
    data = source.read_bytes()
    assert hashlib.sha256(data).hexdigest() == book['sha256'], book['id']
    reader = PdfReader(source)
    assert not reader.is_encrypted and len(reader.pages) == book['pages'], book['id']
    for page in reader.pages:
        assert float(page.mediabox.width) > 0 and float(page.mediabox.height) > 0
    target = ROOT / 'content/originals' / Path(book['asset']).name
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, target)
    keys = ['id','title','author','subject','description','source','asset','publisher','edition','licenseName','licenseUrl','rightsNote','sha256']
    args = [f'{key} = {kotlin(book[key])}' for key in keys]
    schools = book.get('schools', [])
    assert all(s in {'hanafi', 'maliki', 'shafii', 'hanbali'} for s in schools), book['id']
    assert not schools or book['subject'] == 'fiqh', book['id']
    chapters = book.get('chapters', [])
    assert len({c['title'] for c in chapters}) == len(chapters), book['id']
    assert all(1 <= c['pdfPage'] <= book['pages'] and c['printedPage'] and c['title'] in book['topics'] for c in chapters), book['id']
    args += [f'pages = {book["pages"]}', 'downloadUrl = ' + kotlin(book['downloadUrl']), f'bytes = {len(data)}L', 'topics = listOf(' + ', '.join(kotlin(v) for v in book['topics']) + ')',
             'schools = setOf(' + ', '.join(kotlin(v) for v in schools) + ')',
             'chapters = listOf(' + ', '.join('BookChapter(' + kotlin(c['title']) + ', ' + str(c['pdfPage']) + ', ' + kotlin(c['printedPage']) + ')' for c in chapters) + ')']
    rows.append('    Book(\n        ' + ',\n        '.join(args) + '\n    )')
    metadata.append({**book, 'bytes': len(data), 'verifiedOn': book.get('reviewedOn', '2026-10-23')})

generated = '// Generated by tools/package_library.py from content/books.json.\npackage com.algohary.basair\n\ninternal val libraryBooks = listOf(\n' + ',\n'.join(rows) + '\n)\n'
(ROOT / 'app/src/main/java/com/algohary/basair/LibraryData.kt').write_text(generated, encoding='utf-8')
(ROOT / 'app/src/main/assets/library-manifest.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding='utf-8')
(ROOT / 'content/library-audit.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps({'books': len(books), 'pages': sum(b['pages'] for b in books), 'bytes': sum(b['bytes'] for b in metadata), 'checks': 'SHA-256, unencrypted, page count, page dimensions; unchanged original bytes'}, ensure_ascii=False))
